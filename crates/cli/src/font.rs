fn glyph(c: char) -> &'static [&'static str; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?'))
        .map(|(_, rows)| rows)
        .expect("'?' is in the font")
}

/// How wide `text` is when drawn at `scale` (each font pixel becomes a
/// `scale` x `scale` square).
pub fn text_width(text: &str, scale: u32) -> u32 {
    (text.chars().count() as u32 * ADVANCE).saturating_sub(1) * scale
}

/// How high a line of text is at `scale`.
pub fn text_height(scale: u32) -> u32 {
    GLYPH_HEIGHT * scale
}

/// Draws `text` with its top-left corner at (x, y).
pub fn draw_text(image: &mut Image, text: &str, x: i32, y: i32, scale: u32, color: Color) {
    for (i, c) in text.chars().enumerate() {
        let left = x + (i as u32 * ADVANCE * scale) as i32;
        for (row, line) in glyph(c).iter().enumerate() {
            for (column, ink) in line.chars().enumerate() {
                if ink == '#' {
                    image.fill_rect(
                        left + (column as u32 * scale) as i32,
                        y + (row as u32 * scale) as i32,
                        scale,
                        scale,
                        color,
                    );
                }
            }
        }
    }
}

/// `text`, shortened with ".." if needed so it fits in `width` pixels.
pub fn fit_text(text: &str, width: u32, scale: u32) -> String {
    if text_width(text, scale) <= width {
        return text.to_owned();
    }
    let mut short: String = text.to_owned();
    while !short.is_empty() && text_width(&format!("{short}.."), scale) > width {
        short.pop();
    }
    format!("{short}..")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_5_by_7() {
        for (c, rows) in GLYPHS {
            for row in rows {
                assert_eq!(row.len(), 5, "{c:?}");
                assert!(row.chars().all(|p| p == '#' || p == '.'), "{c:?}");
            }
        }
    }

    #[test]
    fn text_is_drawn_where_asked() {
        let mut image = Image::new(20, 10, [0, 0, 0, 255]);
        draw_text(&mut image, "I", 1, 1, 1, [255, 255, 255, 255]);
        // The top bar of the I: columns 1..=3 of the glyph, on row 0.
        assert_eq!(image.pixel(2, 1), [255, 255, 255, 255]);
        assert_eq!(image.pixel(1, 1), [0, 0, 0, 255]);
        assert_eq!(text_width("AB", 2), 22);
    }

    #[test]
    fn long_text_is_shortened_to_fit() {
        let fitted = fit_text("a very long snapshot name", 60, 1);
        assert!(text_width(&fitted, 1) <= 60, "{fitted}");
        assert!(fitted.ends_with(".."));
        assert_eq!(fit_text("ok", 60, 1), "ok");
    }
}
