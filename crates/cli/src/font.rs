//! A tiny pixel font for labels on contact sheets: capital letters,
//! digits and a little punctuation, each 5 pixels wide and 7 high.
//! Small letters are drawn as capitals; anything else as "?".
//!
//! Each letter is drawn below as 7 rows of 5 characters: '#' is ink.

use art_engine::image::{Color, Image};

/// Width and height of one letter, in font pixels.
const GLYPH_WIDTH: u32 = 5;
const GLYPH_HEIGHT: u32 = 7;
/// Letters are this far apart (one empty column between them).
const ADVANCE: u32 = GLYPH_WIDTH + 1;

#[rustfmt::skip]
